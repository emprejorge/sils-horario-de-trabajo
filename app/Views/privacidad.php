    <h1>Política de Privacidad</h1>
    <p><strong>Última actualización:</strong> Abril 2026</p>

    <p>
        En <strong>Sistema de registro de horas laborales</strong>, operado por
        <strong>Scuola Italiana La Serena</strong>, nos comprometemos a proteger la privacidad
        de nuestros usuarios. Esta Política de Privacidad describe cómo recopilamos, usamos
        y protegemos tu información.
    </p>

    <h2>1. Información que recopilamos</h2>
    <p>Podemos recopilar la siguiente información:</p>
    <ul>
        <li>Nombre completo</li>
        <li>Correo electrónico</li>
        <li>Número de teléfono</li>
        <li>Foto de perfil</li>
    </ul>

    <p>
        La autenticación se realiza mediante servicios de terceros como
        :contentReference[oaicite:0]{index=0}, por lo que también podemos acceder a:
    </p>
    <ul>
        <li>Correo electrónico asociado a la cuenta de Google</li>
        <li>Nombre público</li>
        <li>Identificador único de usuario</li>
    </ul>

    <h2>2. Uso de la información</h2>
    <p>La información recopilada se utiliza para:</p>
    <ul>
        <li>Permitir el acceso seguro a la plataforma</li>
        <li>Registrar y gestionar horas laborales</li>
        <li>Mejorar la experiencia del usuario</li>
        <li>Comunicación relacionada con el servicio</li>
    </ul>

    <h2>3. Compartición de datos</h2>
    <p>
        No vendemos ni compartimos datos personales con terceros, salvo en los siguientes casos:
    </p>
    <ul>
        <li>Cuando sea requerido por ley</li>
        <li>Para el funcionamiento técnico del sistema (hosting o infraestructura)</li>
    </ul>

    <h2>4. Servicios de terceros</h2>
    <p>Utilizamos servicios externos como:</p>
    <ul>
        <li>Hosting de Powerhost.cl</li>
    </ul>

    <p>
        Estos servicios pueden procesar datos conforme a sus propias políticas de privacidad.
    </p>

    <h2>5. Seguridad de la información</h2>
    <p>
        Implementamos medidas de seguridad para proteger los datos personales contra accesos
        no autorizados, pérdida o alteración.
    </p>

    <h2>6. Retención de datos</h2>
    <p>
        Los datos se almacenan mientras la cuenta del usuario esté activa o mientras sean
        necesarios para el funcionamiento del sistema.
    </p>

    <h2>7. Derechos del usuario</h2>
    <p>El usuario puede:</p>
    <ul>
        <li>Solicitar acceso a sus datos</li>
        <li>Solicitar modificación o eliminación</li>
    </ul>

    <h2>8. Eliminación de cuenta</h2>
    <p>
        La eliminación de cuentas debe solicitarse mediante correo electrónico a:
        <br><strong>informatica@scuolaitalianalaserena.cl</strong>
    </p>

    <h2>9. Cambios a esta política</h2>
    <p>
        Nos reservamos el derecho de modificar esta política en cualquier momento.
    </p>

